#Operadores aritmeticos

x = 5
y = 3

#Suma
print("Suma:", x + y) # Imprime 8 por que es la suma de 5 y 3

#Resta
print("Resta:", x - y) # Imprime 2 por que es la resta de 5 y 3

#Multiplicacion
print("Multiplicacion:", x * y) # Imprime 15 por que es la multiplicacion de 5 y 3

#Division
print("Division:", x / y) # Imprime 1.6666666666666667 por que es la division de 5 y 3

#modulo
print("Modulo:", x % y) # Imprime 2 por que es el residuo de la division de 5 y 3

#Exponente
print("Exponente:", x ** y) # Imprime 125 por que es el exponente de 5 y 3

#potencia
print("Potencia:", pow(x, y)) # Imprime 125 por que es la potencia de 5 y 3

#division entera
print("Division entera:", x // y) # Imprime 1 por que es la division entera de 5 y 3

#presencia de un operador
print("Presencia de un operador:", x > y) # Imprime True por que 5 es mayor que 3
print("Presencia de un operador:", x < y) # Imprime False por que 5 no es menor que 3
print("Presencia de un operador:", x == y) # Imprime False por que 5 no es igual a 3
print("Presencia de un operador:", x != y) # Imprime True por que 5 no es igual a 3

