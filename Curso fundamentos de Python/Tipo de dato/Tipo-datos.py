#strings
comillasSimples = 'Esto es un texto con comillas simples'
comillasDobles = "Esto es un texto con comillas dobles"
comillasTriples = '''Esto es un texto con comillas triples, se puede usar para escribir un texto de varias lineas'''
print(comillasSimples)
print(comillasDobles)
print(comillasTriples)

#numeros
a = 5 # Esto es un numero entero
b = 5.5 # Esto es un numero decimal 
c = 5 + 2j # Esto es un numero complejo
print(a)
print(b)
print(c)

#listas
lista = [1, 2, 3, 4, 5] # Esto es una lista de numeros
lista2 = ["a", "b", "c", "d", "e"] # Esto es una lista de letras
print(lista)
print(lista2)

#tuplas
tupla = (1, 2, 3, 4, 5) # Esto es una tupla de numeros
tupla2 = ("a", "b", "c", "d", "e") # Esto es una tupla de letras
print(tupla)
print(tupla2)

#diccionarios
diccionario = {
    "clave1": "valor1",
    "clave2": 30,
    "clave3": "valor3"
} # Esto es un diccionario
print(diccionario)

#conjuntos (sets)
conjunto = {1, 2, 3, 3, 4, 5} # Esto es un conjunto de numeros, no lee numeros o caracteres repetidos, no tiene un orden especifico y no se puede acceder a sus elementos por indice
conjunto2 = {"a", "b", "c", "d", "e"} # Esto es un conjunto de letras
print(conjunto)
print(conjunto2)

#booleanos
booleano = True # Esto es un valor booleano
booleano2 = False # Esto es un valor booleano
print(booleano)
print(booleano2)