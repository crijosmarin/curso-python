# None

x = None # Esto es una variable con valor nulo, no tiene ningun valor asignado
print(x) # Imprime None por que es una variable con valor nulo
print(type(x)) # Imprime <class 'NoneType'> por que es una variable con valor nulo
print(type("Hola")) # Imprime <class 'str'> por que es una variable con valor de tipo string
print(type(5)) # Imprime <class 'int'> por que es una variable con valor de tipo entero
print(type(5.5)) # Imprime <class 'float'> por que es una variable con valor de tipo decimal
print(type(False)) # Imprime <class 'bool'> por que es una variable con valor de tipo booleano
print(type([1, 2, 3])) # Imprime <class 'list'> por que es una variable con valor de tipo lista
